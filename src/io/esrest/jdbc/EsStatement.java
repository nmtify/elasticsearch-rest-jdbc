package io.esrest.jdbc;

import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.SQLWarning;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Executes three kinds of statements: Elasticsearch SQL queries, DML (INSERT/UPDATE/DELETE, see {@link EsDml})
 * and raw REST requests such as {@code GET /_cat/indices}.
 */
class EsStatement extends JdbcWrapper implements Statement {
    private static final Pattern REST_REQUEST = Pattern.compile(
            "^(GET|POST|PUT|DELETE|HEAD)\\s+(/\\S*)(?:\\s+([\\s\\S]*))?$", Pattern.CASE_INSENSITIVE);

    final EsConnection connection;
    private final List<String> batch = new ArrayList<>();
    private EsResultSet currentResultSet;
    private int updateCount = -1;
    private int maxRows;
    private int fetchSize;
    private int queryTimeoutSeconds;
    private boolean closeOnCompletion;
    private boolean closed;

    EsStatement(EsConnection connection) {
        this.connection = connection;
    }

    void checkOpen() throws SQLException {
        if (closed) {
            throw new SQLException("Statement is closed", "HY010");
        }
        connection.checkOpen();
    }

    /** Runs a statement; returns true when it produced a result set, false when it produced an update count. */
    boolean run(String sql, List<Map<String, Object>> params) throws SQLException {
        checkOpen();
        closeCurrentResultSet();
        updateCount = -1;

        String statement = stripTrailingSemicolons(sql);
        if (statement.isEmpty()) {
            throw new SQLException("Empty query", "42000");
        }

        Matcher rest = REST_REQUEST.matcher(statement);
        if (rest.matches()) {
            currentResultSet = connection.executeRest(rest.group(1), rest.group(2), rest.group(3), this, maxRows);
            return true;
        }
        if (EsDml.isDml(statement)) {
            updateCount = connection.executeDml(statement, params);
            return false;
        }
        String query = SqlRewriter.rewrite(statement);
        currentResultSet = connection.executeQuery(query, params, this, fetchSize, maxRows, queryTimeoutSeconds);
        return true;
    }

    int runUpdate(String sql, List<Map<String, Object>> params) throws SQLException {
        if (!run(sql, params)) {
            return Math.max(updateCount, 0);
        }
        closeCurrentResultSet();
        throw new SQLException("executeUpdate() cannot run a query; use executeQuery()", "07000");
    }

    void resultSetClosed(EsResultSet resultSet) throws SQLException {
        if (resultSet == currentResultSet && closeOnCompletion) {
            close();
        }
    }

    private static String stripTrailingSemicolons(String sql) {
        String statement = sql == null ? "" : sql.trim();
        while (statement.endsWith(";")) {
            statement = statement.substring(0, statement.length() - 1).trim();
        }
        return statement;
    }

    private void closeCurrentResultSet() throws SQLException {
        if (currentResultSet == null) {
            return;
        }
        EsResultSet resultSet = currentResultSet;
        currentResultSet = null;
        resultSet.close();
    }

    // ---------------------------------------------------------------- execution

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        run(sql, null);
        return currentResultSet;
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        return run(sql, null);
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        return execute(sql);
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        return execute(sql);
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        return execute(sql);
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        return runUpdate(sql, null);
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        return executeUpdate(sql);
    }

    @Override
    public void addBatch(String sql) throws SQLException {
        checkOpen();
        batch.add(sql);
    }

    @Override
    public void clearBatch() {
        batch.clear();
    }

    @Override
    public int[] executeBatch() throws SQLException {
        checkOpen();
        try {
            int[] counts = new int[batch.size()];
            for (int i = 0; i < counts.length; i++) {
                counts[i] = runUpdate(batch.get(i), null);
            }
            return counts;
        } finally {
            batch.clear();
        }
    }

    @Override
    public ResultSet getResultSet() {
        return currentResultSet;
    }

    @Override
    public int getUpdateCount() {
        return updateCount;
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        closeCurrentResultSet();
        updateCount = -1;
        return false;
    }

    @Override
    public boolean getMoreResults(int current) throws SQLException {
        return getMoreResults();
    }

    @Override
    public ResultSet getGeneratedKeys() throws SQLException {
        throw unsupported();
    }

    @Override
    public void cancel() throws SQLException {
        closeCurrentResultSet();
    }

    @Override
    public void close() throws SQLException {
        if (closed) {
            return;
        }
        closeCurrentResultSet();
        closed = true;
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public void closeOnCompletion() {
        closeOnCompletion = true;
    }

    @Override
    public boolean isCloseOnCompletion() {
        return closeOnCompletion;
    }

    // ---------------------------------------------------------------- settings

    @Override
    public int getMaxRows() {
        return maxRows;
    }

    @Override
    public void setMaxRows(int maxRows) {
        this.maxRows = Math.max(0, maxRows);
    }

    @Override
    public int getFetchSize() {
        return fetchSize > 0 ? fetchSize : connection.config.fetchSize;
    }

    @Override
    public void setFetchSize(int rows) {
        this.fetchSize = Math.max(0, rows);
    }

    @Override
    public int getQueryTimeout() {
        return queryTimeoutSeconds;
    }

    @Override
    public void setQueryTimeout(int seconds) {
        this.queryTimeoutSeconds = Math.max(0, seconds);
    }

    @Override
    public int getMaxFieldSize() {
        return 0;
    }

    @Override
    public void setMaxFieldSize(int max) { }

    @Override
    public void setEscapeProcessing(boolean enable) { }

    @Override
    public void setCursorName(String name) throws SQLException {
        throw unsupported();
    }

    @Override
    public void setFetchDirection(int direction) { }

    @Override
    public int getFetchDirection() {
        return ResultSet.FETCH_FORWARD;
    }

    @Override
    public int getResultSetConcurrency() {
        return ResultSet.CONCUR_READ_ONLY;
    }

    @Override
    public int getResultSetType() {
        return ResultSet.TYPE_FORWARD_ONLY;
    }

    @Override
    public int getResultSetHoldability() {
        return ResultSet.CLOSE_CURSORS_AT_COMMIT;
    }

    @Override
    public void setPoolable(boolean poolable) { }

    @Override
    public boolean isPoolable() {
        return false;
    }

    @Override
    public SQLWarning getWarnings() {
        return null;
    }

    @Override
    public void clearWarnings() { }

    @Override
    public Connection getConnection() {
        return connection;
    }
}
